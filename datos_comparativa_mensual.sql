-- Ver resumen por mes
SELECT 
    DATE_FORMAT(fecha, '%Y-%m') as mes,
    COUNT(*) as total_registros,
    ROUND(AVG(kwh), 2) as promedio_kwh,
    ROUND(MIN(kwh), 2) as minimo_kwh,
    ROUND(MAX(kwh), 2) as maximo_kwh,
    ROUND(SUM(kwh), 2) as total_kwh_mes
FROM energia 
WHERE fecha >= '2024-01-01' 
GROUP BY DATE_FORMAT(fecha, '%Y-%m')
ORDER BY mes;

