-- 1. ELIMINAR DATOS CORRUPTOS (valores irreales)
DELETE FROM energia 
WHERE kwh > 1000  -- Eliminar lecturas con más de 1000 kWh (irreal)
   OR voltaje > 300  -- Eliminar voltajes irreales
   OR voltaje < 100  -- Eliminar voltajes muy bajos
   OR corriente > 50  -- Eliminar corrientes irreales
   OR potencia > 50000; -- Eliminar potencias irreales

-- 2. VERIFICAR DATOS RESTANTES
SELECT 
    COUNT(*) as total_registros,
    MIN(kwh) as minimo_kwh,
    MAX(kwh) as maximo_kwh,
    AVG(kwh) as promedio_kwh,
    MIN(voltaje) as minimo_voltaje,
    MAX(voltaje) as maximo_voltaje,
    MIN(corriente) as minimo_corriente,
    MAX(corriente) as maximo_corriente
FROM energia;

